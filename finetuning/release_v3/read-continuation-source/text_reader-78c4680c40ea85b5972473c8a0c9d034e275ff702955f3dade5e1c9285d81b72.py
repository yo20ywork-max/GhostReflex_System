"""Bounded-memory text segments and mechanical whole-file coverage checks."""
import codecs
import hashlib
import os
import re
from pathlib import Path


def _version(stat):
    return stat.st_dev, stat.st_ino, stat.st_size, stat.st_mtime_ns, stat.st_ctime_ns


def read_text_segment(path, max_chars=50000, offset_chars=0, expected_sha256='', cancel_event=None):
    if type(offset_chars) is not int or offset_chars < 0:
        raise ValueError('offset_chars 必須是非負整數。')
    if type(max_chars) is not int or not 100 <= max_chars <= 500000:
        raise ValueError('max_chars 必須介於100與500000。')
    if expected_sha256 and not re.fullmatch('[0-9a-f]{64}', expected_sha256):
        raise ValueError('expected_sha256 格式不正確。')
    if offset_chars and not expected_sha256:
        raise ValueError('接續讀取必須提供前段的 expected_sha256，避免混用不同版本。')
    path = Path(path)
    for encoding in ('utf-8', 'utf-8-sig', 'big5', 'cp950'):
        decoder = codecs.getincrementaldecoder(encoding)(errors='strict')
        digest, pieces, total = hashlib.sha256(), [], 0
        try:
            with path.open('rb') as stream:
                before = _version(os.fstat(stream.fileno()))

                def consume(text):
                    nonlocal total
                    left = max(0, offset_chars - total)
                    right = min(len(text), offset_chars + max_chars - total)
                    if left < right:
                        pieces.append(text[left:right])
                    total += len(text)

                while True:
                    if cancel_event is not None and cancel_event.is_set():
                        raise ValueError('已取消讀取，未提供不完整片段。')
                    raw = stream.read(65536)
                    if not raw:
                        break
                    digest.update(raw)
                    consume(decoder.decode(raw))
                consume(decoder.decode(b'', final=True))
                # Windows CPython may expose different ctime semantics for
                # fstat versus stat. Compare ctime only within the handle API.
                if before != _version(os.fstat(stream.fileno())) or before[:4] != _version(path.stat())[:4]:
                    raise ValueError('讀取期間檔案已變更，這次片段不能作為完整證據。')
        except UnicodeDecodeError:
            continue
        sha = digest.hexdigest()
        if expected_sha256 and sha != expected_sha256:
            raise ValueError('檔案內容雜湊與前段不同；請從頭讀取新版本，不得拼接舊片段。')
        if offset_chars > total:
            raise ValueError('接續位置超過檔案字元總數。')
        text = ''.join(pieces)
        end = offset_chars + len(text)
        return text, {'path': str(path.resolve()), 'chars': total, 'truncated': end < total,
                      'read_extent': {'version': 1, 'kind': 'whole_file_segment', 'sha256': sha,
                                      'encoding': encoding, 'total_chars': total, 'start': offset_chars, 'end': end,
                                      'next_offset_chars': end if end < total else None}}
    raise ValueError('無法辨識文字編碼。')


def uncovered_file_reads(history):
    """Find gaps in the latest observed version of each whole-file read.

    Extents are generated by the trusted handler, not supplied by the model.
    This proves acquisition coverage, not that the model understood the file or
    that the requested downstream transformation is correct.
    """
    versions = {}
    for index, item in enumerate(history, 1):
        if item.get('tool') != 'READ_TEXT_FILE' or item.get('ok') is not True:
            continue
        evidence = item.get('evidence') or {}
        extent = evidence.get('read_extent')
        if not extent:
            if evidence.get('truncated') is True:
                path = evidence.get('path')
                if not isinstance(path, str):
                    return [{'reason': '舊讀取證據已截斷且沒有可核對的來源。', 'sequence': index}]
                versions[path] = {'sha256': None, 'legacy_sequence': index}
            elif evidence.get('truncated') is False and isinstance(evidence.get('path'), str):
                versions.pop(evidence['path'], None)
            continue
        path = evidence.get('path')
        if not isinstance(extent, dict) or extent.get('version') != 1 or extent.get('kind') != 'whole_file_segment' or not isinstance(path, str):
            return [{'reason': '讀取範圍證據格式錯誤。', 'sequence': index}]
        start, end, total, sha = (extent.get(k) for k in ('start', 'end', 'total_chars', 'sha256'))
        if (any(type(v) is not int for v in (start, end, total)) or not 0 <= start <= end <= total
                or not isinstance(sha, str) or not re.fullmatch('[0-9a-f]{64}', sha)
                or not isinstance(item.get('output'), str) or len(item['output']) != end - start
                or item.get('verified') is not True):
            return [{'reason': '讀取片段與範圍證據不一致。', 'sequence': index}]
        current = versions.get(path)
        if current is None or current['sha256'] != sha:
            current = versions[path] = {'sha256': sha, 'total_chars': total, 'ranges': []}
        if current['total_chars'] != total:
            return [{'reason': '相同版本的字元總數不一致。', 'sequence': index}]
        current['ranges'].append((start, end))
    gaps = []
    for path, item in versions.items():
        if item['sha256'] is None:
            gaps.append({'path': path, 'reason': '舊读取已截斷，需重新取得完整範圍證據。', 'sequence': item['legacy_sequence']})
            continue
        cursor = 0
        for start, end in sorted(item['ranges']):
            if start > cursor:
                gaps.append({'path': path, 'sha256': item['sha256'], 'start': cursor, 'end': start})
            cursor = max(cursor, end)
        if cursor < item['total_chars']:
            gaps.append({'path': path, 'sha256': item['sha256'], 'start': cursor, 'end': item['total_chars']})
    return gaps
