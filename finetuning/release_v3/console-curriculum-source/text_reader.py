"""Bounded-memory text segments and mechanical whole-file coverage checks."""
import codecs
import hashlib
import os
import re
from pathlib import Path


def _version(stat):
    return stat.st_dev, stat.st_ino, stat.st_size, stat.st_mtime_ns, stat.st_ctime_ns


def read_text_segment(path, max_chars=50000, offset_chars=0, expected_sha256='', cancel_event=None):
    if type(offset_chars) is not int or offset_chars < 0:
        raise ValueError('offset_chars 必須是非負整數。')
    if type(max_chars) is not int or not 100 <= max_chars <= 500000:
        raise ValueError('max_chars 必須介於100與500000。')
    if expected_sha256 and not re.fullmatch('[0-9a-f]{64}', expected_sha256):
        raise ValueError('expected_sha256 格式不正確。')
    if offset_chars and not expected_sha256:
        raise ValueError('接續讀取必須提供前段的 expected_sha256，避免混用不同版本。')
    path = Path(path)
    for encoding in ('utf-8', 'utf-8-sig', 'big5', 'cp950'):
        decoder = codecs.getincrementaldecoder(encoding)(errors='strict')
        digest, pieces, total = hashlib.sha256(), [], 0
        try:
            with path.open('rb') as stream:
                before = _version(os.fstat(stream.fileno()))

                def consume(text):
                    nonlocal total
                    left = max(0, offset_chars - total)
                    right = min(len(text), offset_chars + max_chars - total)
                    if left < right:
                        pieces.append(text[left:right])
                    total += len(text)

                while True:
                    if cancel_event is not None and cancel_event.is_set():
                        raise ValueError('已取消讀取，未提供不完整片段。')
                    raw = stream.read(65536)
                    if not raw:
                        break
                    digest.update(raw)
                    consume(decoder.decode(raw))
                consume(decoder.decode(b'', final=True))
                # Windows CPython may expose different ctime semantics for
                # fstat versus stat. Compare ctime only within the handle API.
                if before != _version(os.fstat(stream.fileno())) or before[:4] != _version(path.stat())[:4]:
                    raise ValueError('讀取期間檔案已變更，這次片段不能作為完整證據。')
        except UnicodeDecodeError:
            continue
        sha = digest.hexdigest()
        if expected_sha256 and sha != expected_sha256:
            raise ValueError('檔案內容雜湊與前段不同；請從頭讀取新版本，不得拼接舊片段。')
        if offset_chars > total:
            raise ValueError('接續位置超過檔案字元總數。')
        text = ''.join(pieces)
        end = offset_chars + len(text)
        return text, {'path': str(path.resolve()), 'chars': total, 'truncated': end < total,
                      'read_extent': {'version': 1, 'kind': 'whole_file_segment', 'sha256': sha,
                                      'encoding': encoding, 'total_chars': total, 'start': offset_chars, 'end': end,
                                      'next_offset_chars': end if end < total else None}}
    raise ValueError('無法辨識文字編碼。')


def uncovered_file_reads(history):
    """Find gaps in the latest observed version of each whole-file read.

    Extents are generated by the trusted handler, not supplied by the model.
    This proves acquisition coverage, not that the model understood the file or
    that the requested downstream transformation is correct.
    """
    versions = {}
    for index, item in enumerate(history, 1):
        if item.get('tool') != 'READ_TEXT_FILE' or item.get('ok') is not True:
            continue
        evidence = item.get('evidence') or {}
        extent = evidence.get('read_extent')
        if not extent:
            if evidence.get('truncated') is True:
                path = evidence.get('path')
                if not isinstance(path, str):
                    return [{'reason': '舊讀取證據已截斷且沒有可核對的來源。', 'sequence': index}]
                versions[path] = {'sha256': None, 'legacy_sequence': index}
            elif evidence.get('truncated') is False and item.get('verified') is True and isinstance(item.get('output'), str) and isinstance(evidence.get('path'), str):
                versions.pop(evidence['path'], None)
            continue
        path = evidence.get('path')
        if not isinstance(extent, dict) or extent.get('version') != 1 or extent.get('kind') != 'whole_file_segment' or not isinstance(path, str):
            return [{'reason': '讀取範圍證據格式錯誤。', 'sequence': index}]
        start, end, total, sha = (extent.get(k) for k in ('start', 'end', 'total_chars', 'sha256'))
        if (any(type(v) is not int for v in (start, end, total)) or not 0 <= start <= end <= total
                or not isinstance(sha, str) or not re.fullmatch('[0-9a-f]{64}', sha)
                or not isinstance(item.get('output'), str) or len(item['output']) != end - start
                or item.get('verified') is not True):
            return [{'reason': '讀取片段與範圍證據不一致。', 'sequence': index}]
        current = versions.get(path)
        if current is None or current['sha256'] != sha:
            current = versions[path] = {'sha256': sha, 'total_chars': total, 'ranges': []}
        if current['total_chars'] != total:
            return [{'reason': '相同版本的字元總數不一致。', 'sequence': index}]
        current['ranges'].append((start, end))
    gaps = []
    for path, item in versions.items():
        if item['sha256'] is None:
            gaps.append({'path': path, 'reason': '舊读取已截斷，需重新取得完整範圍證據。', 'sequence': item['legacy_sequence']})
            continue
        cursor = 0
        for start, end in sorted(item['ranges']):
            if start > cursor:
                gaps.append({'path': path, 'sha256': item['sha256'], 'start': cursor, 'end': start})
            cursor = max(cursor, end)
        if cursor < item['total_chars']:
            gaps.append({'path': path, 'sha256': item['sha256'], 'start': cursor, 'end': item['total_chars']})
    return gaps


def file_read_progress(history):
    """Expose checked acquisition facts to both planning and completion."""
    gaps = uncovered_file_reads(history)
    if any('reason' in gap for gap in gaps):
        return {'validated': False, 'issues': gaps, 'files': []}
    files = {}
    for item in history:
        details = item.get('evidence') or {}
        extent = details.get('read_extent')
        if item.get('tool') != 'READ_TEXT_FILE' or item.get('ok') is not True:
            continue
        if not extent:
            files.pop(details.get('path'), None)
            continue
        path = details['path']
        files[path] = {'path': path, 'request_path': item.get('args', {}).get('path'),
                       'sha256': extent['sha256'], 'total_chars': extent['total_chars']}
    for path, record in files.items():
        record['missing_ranges'] = [{'start': g['start'], 'end': g['end']} for g in gaps if g.get('path') == path]
        record['whole_file_observed'] = not record['missing_ranges']
        record['next_reads'] = [{'path': record['request_path'] or path, 'offset_chars': g['start'],
                                 'max_chars': max(100, min(500000, g['end'] - g['start'])),
                                 'expected_sha256': record['sha256']} for g in record['missing_ranges']]
    return {'validated': True, 'issues': [], 'files': list(files.values()),
            'scope': 'Content acquisition only; not proof of downstream work or overall task completion.'}


def validate_read_continuations(plan, history):
    """Reject impossible continuation positions before any planned dispatch.

    Do not silently repair, remove or execute a different step. The planner gets
    the error and actual source facts. A file may still change after this check;
    the handler's content hash check remains authoritative at execution time.
    """
    progress = file_read_progress(history)
    known = {}
    if progress['validated']:
        for item in progress['files']:
            for path in (item['path'], item['request_path']):
                if path is not None:
                    known[path] = item
    for step in plan.steps:
        if step.tool != 'READ_TEXT_FILE':
            continue
        args = step.args
        start = args.get('offset_chars', 0)
        if type(start) is not int or start == 0:
            continue  # References/types are independently validated at dispatch.
        path = args.get('path');source = known.get(path) if isinstance(path, str) else None
        if source is None:
            raise ValueError('接續讀取前需要該檔案的已驗證來源、長度與內容雜湊。')
        if args.get('expected_sha256') != source['sha256']:
            raise ValueError('接續讀取的 expected_sha256 必須符合該檔案最新觀察版本。')
        if not 0 <= start < source['total_chars']:
            raise ValueError(f'接續位置 {start} 超出可讀取範圍 [0,{source["total_chars"]})；EOF位置沒有尚待讀取的內容。')


def completed_file_contents(history):
    """Assemble verified complete versions without pretending another read ran.

    Original chronological observations remain untouched. Overlap must agree;
    source positions and original sequence indices accompany every derived text.
    """
    progress = file_read_progress(history)
    if not progress['validated']:
        return {}
    assembled = {}
    for info in progress['files']:
        if not info['whole_file_observed']:
            continue
        parts = []
        # Mirror the latest contiguous version epoch used by the range checker.
        for index, item in enumerate(history, 1):
            evidence = item.get('evidence') or {}
            if item.get('tool') != 'READ_TEXT_FILE' or item.get('ok') is not True or evidence.get('path') != info['path']:
                continue
            extent = evidence.get('read_extent')
            if not extent or extent.get('sha256') != info['sha256']:
                parts = []
                continue
            parts.append((extent['start'], extent['end'], item['output'], index, extent.get('encoding')))
        text = ''; witnesses = []; encoding = None
        for start, end, fragment, index, current_encoding in sorted(parts):
            if encoding is None:
                encoding = current_encoding
            elif current_encoding != encoding:
                raise ValueError('相同檔案片段的編碼不一致。')
            if start > len(text):
                raise ValueError('全文組合仍有缺少範圍。')
            overlap = min(end, len(text)) - start
            if text[start:start + overlap] != fragment[:overlap]:
                raise ValueError('重疊讀取片段不一致，不得組合為全文。')
            text += fragment[overlap:]
            witnesses.append({'sequence_index': index, 'start': start, 'end': end})
        if len(text) != info['total_chars']:
            raise ValueError('全文組合長度不符。')
        assembled[info['path']] = {'sha256': info['sha256'], 'total_chars': info['total_chars'], 'text': text,
                                  'source_segments': witnesses, 'derived_from_observations': True, 'new_dispatch': False}
    return assembled


def file_text_from_step(step_id, history):
    """Resolve an explicit full-text reference to the anchor's observed version.

    No I/O or extra dispatch occurs. Never substitute a newer observed version
    for the requested anchor, even when an intervening change later reverts.
    """
    matches = [(index, item) for index, item in enumerate(history, 1) if item.get('step_id') == step_id]
    if len(matches) != 1:
        raise ValueError('全文引用需要唯一的已觀察讀取步驟。')
    index, anchor = matches[0]
    if anchor.get('tool') != 'READ_TEXT_FILE' or anchor.get('ok') is not True or anchor.get('verified') is not True:
        raise ValueError('全文引用只能指向成功且已驗證的 READ_TEXT_FILE。')
    evidence = anchor.get('evidence') or {}
    extent = evidence.get('read_extent') or {}
    content = completed_file_contents(history).get(evidence.get('path'))
    if content is None or content['sha256'] != extent.get('sha256'):
        raise ValueError('該引用版本的全文尚未取得，或最新觀察已變更；不得替換版本。')
    if not any(part['sequence_index'] == index for part in content['source_segments']):
        raise ValueError('全文引用來自較早觀察版本，不得跨越已知檔案變更組合。')
    return content['text']


def available_file_text_references(history):
    """Expose usable references derived from verified current-version segments."""
    contents = completed_file_contents(history)
    references = []
    for path, content in contents.items():
        for part in content['source_segments']:
            item = history[part['sequence_index'] - 1]
            step_id = item.get('step_id')
            if type(step_id) is not int or step_id < 1:
                continue
            if sum(row.get('step_id') == step_id for row in history) != 1:
                continue
            references.append({'path': path, 'sha256': content['sha256'], 'total_chars': content['total_chars'],
                               'reference': '{{step:' + str(step_id) + '.file_text}}'})
            break
    return references
